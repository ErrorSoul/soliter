-- debug_flags.lua — одна точка правды про «это отладочная сборка или релизная».
--
-- Блок D. Ревью блока H обеими моделями подняло клавиши S / R / Space до
-- блокера релиза: в js-web они живые, и на десктопе (в том числе у модератора
-- Я.Игр) S считает солвер прямо в главном потоке, R отдаёт партию автоигроку,
-- Space перезапускает уровень.
--
-- Ветки НЕ вырезаем, а закрываем флагом: те же клавиши — рабочий инструмент
-- стенда (tools/browser-test.py гоняет раздачи клавишей Space и решает партию
-- клавишей R). Вырезать их значит остаться без сквозных проверок.
--
-- Источник флага — sys.get_engine_info().is_debug: он приходит от САМОГО
-- движка и отражает вариант сборки (bob --variant debug/release), а не
-- переменную, которую забудут переключить. Замерено на двух настоящих бандлах:
-- debug → true, release → false.
--
-- game.project можно было бы завести отдельным ключом, но тогда флаг снова
-- пришлось бы помнить руками — а забытый true и есть причина этой правки.

local M = {}

local ok, info = pcall(sys.get_engine_info)
M.enabled = (ok and info and info.is_debug) and true or false

return M
